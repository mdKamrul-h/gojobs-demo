export function getApplicationById(id: string): Application | undefined {
  return applications.find((a) => a.id === id);
}

export function getApplicationsByJobId(jobId: string): Application[] {
  return applications.filter((a) => a.jobId === jobId);
}

export function getApplicationsByCandidateId(candidateId: string): Application[] {
  return applications.filter((a) => a.candidateId === candidateId);
}

/** Count non-rejected applications for a job (excludes rejected stage). */
export function getApplicantCountByJobId(jobId: string): number {
  return applications.filter((a) => a.jobId === jobId && a.stage !== "rejected").length;
}
