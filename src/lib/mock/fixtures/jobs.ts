export function getJobById(id: string): Job | undefined {
  return jobs.find((j) => j.id === id);
}

export function getJobBySlug(slug: string): Job | undefined {
  return jobs.find((j) => j.slug === slug);
}

export function getJobsByCompanyId(companyId: string): Job[] {
  return jobs.filter((j) => j.companyId === companyId && j.status === "published");
}

export function getFeaturedJobs(): Job[] {
  return jobs.filter((j) => j.featured && j.status === "published");
}
